const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('hub', {
  config: () => ipcRenderer.invoke('hub:config'),
  cores: () => ipcRenderer.invoke('hub:cores'),
  agenda: (dias) => ipcRenderer.invoke('hub:agenda', dias),
  salvarContas: (contas) => ipcRenderer.invoke('hub:contas:salvar', contas),
  salvarExtras: (extras) => ipcRenderer.invoke('hub:extras:salvar', extras),
  espelhar: () => ipcRenderer.invoke('hub:espelhar'),
  google: {
    listar: () => ipcRenderer.invoke('hub:google:listar'),
    salvar: (fonte) => ipcRenderer.invoke('hub:google:salvar', fonte),
    autorizar: (nome, escrita) => ipcRenderer.invoke('hub:google:autorizar', nome, escrita),
    calendarios: (nome) => ipcRenderer.invoke('hub:google:calendarios', nome),
    remover: (nome) => ipcRenderer.invoke('hub:google:remover', nome),
  },
  skills: {
    listar: () => ipcRenderer.invoke('skills:listar'),
    favorito: (nome, ligado) => ipcRenderer.invoke('skills:favorito', nome, ligado),
    escolherPasta: (atual) => ipcRenderer.invoke('skills:escolher-pasta', atual),
    rodar: (pedido) => ipcRenderer.invoke('skills:rodar', pedido),
    cancelar: (id) => ipcRenderer.invoke('skills:cancelar', id),
    continuar: (id) => ipcRenderer.invoke('skills:continuar', id),
    historico: () => ipcRenderer.invoke('skills:historico'),
    execucao: (id) => ipcRenderer.invoke('skills:execucao', id),
    salvarConfig: (c) => ipcRenderer.invoke('skills:config:salvar', c),
    atualizar: () => ipcRenderer.invoke('skills:atualizar'),
    ocultas: (lista) => ipcRenderer.invoke('skills:ocultas', lista),
    onAtualizada: (cb) => ipcRenderer.on('skills:atualizada', (_e, d) => cb(d)),
    onEvento: (cb) => ipcRenderer.on('skills:evento', (_e, d) => cb(d)),
    onFim: (cb) => ipcRenderer.on('skills:fim', (_e, d) => cb(d)),
  },
  claude: {
    contas: () => ipcRenderer.invoke('claude:contas'),
    adicionar: (conta) => ipcRenderer.invoke('claude:conta:adicionar', conta),
    login: (id) => ipcRenderer.invoke('claude:conta:login', id),
    remover: (id) => ipcRenderer.invoke('claude:conta:remover', id),
  },
  upd: {
    estado: () => ipcRenderer.invoke('upd:estado'),
    verificar: () => ipcRenderer.invoke('upd:verificar'),
    baixar: () => ipcRenderer.invoke('upd:baixar'),
    instalar: () => ipcRenderer.invoke('upd:instalar'),
    pular: () => ipcRenderer.invoke('upd:pular'),
    auto: (ligado) => ipcRenderer.invoke('upd:auto', ligado),
    changelog: () => ipcRenderer.invoke('upd:changelog'),
    onEstado: (cb) => ipcRenderer.on('upd:estado', (_e, d) => cb(d)),
  },
  badges: (porConta) => ipcRenderer.send('hub:badges', porConta),
  notify: (msg) => ipcRenderer.send('hub:notify', msg),
  openExternal: (url) => ipcRenderer.send('hub:open-external', url),
  onFocusTab: (cb) => ipcRenderer.on('hub:focus-tab', (_e, tab) => cb(tab)),
});
